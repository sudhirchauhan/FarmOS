import { expect, test } from '@playwright/test';

test('available nutrients and exclusive biomass allocations persist and over-allocation fails', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Farm name', { exact: true }).fill(`Browser test nutrient ${Date.now()}`);
  await page.getByLabel('First planning day').fill('2026-01-01');
  await page.getByRole('button', { name: '+ Add cohort' }).click();
  await page.getByLabel('Crop / variety').fill('Amaranth');
  await page.getByLabel('Harvest duration').fill('1');
  await page.getByLabel('Gross cycle yield').fill('5');
  await page.getByText('Crop light response and resource requirements', { exact: true }).click();
  await page.getByLabel('N removal · g / gross kg', { exact: true }).fill('1');
  await page.getByLabel('P removal · g / gross kg', { exact: true }).fill('0');
  await page.getByLabel('K removal · g / gross kg', { exact: true }).fill('0');
  await page.getByLabel('Enable nutrient and biomass budget', { exact: true }).check();
  await page.getByLabel('Opening nutrient source / assumption').fill('Explicit zero pool for test, not measured soil');
  await page.getByRole('button', { name: '+ Add biomass batch' }).click();
  await page.getByLabel('Feedstock name', { exact: true }).fill('Synthetic compost batch');
  await page.getByLabel('Feedstock source note').fill('Synthetic composition, not field validated');
  await page.getByLabel('N content · g / dry kg', { exact: true }).fill('10');
  await page.getByLabel('N available fraction', { exact: true }).fill('0.25');
  await page.getByLabel('P content · g / dry kg', { exact: true }).fill('0');
  await page.getByLabel('K content · g / dry kg', { exact: true }).fill('0');
  await page.getByRole('button', { name: '+ Allocate biomass' }).click();
  await page.getByLabel('Allocation dry mass · kg', { exact: true }).fill('60');
  await page.getByRole('button', { name: '+ Allocate biomass' }).click();
  await page.getByLabel('Allocation purpose').nth(1).selectOption('mulch');
  await page.getByLabel('Allocation dry mass · kg', { exact: true }).nth(1).fill('40');
  const created = page.waitForResponse(r => r.url().includes('/api/scenario-runs/') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Save and calculate 104 weeks' }).click();
  const response = await created;
  expect(response.status()).toBe(201);
  const data = await response.json();
  const nitrogen = data.result.weeks[0].resources.nutrients.elements.n;
  expect(nitrogen.total_compost_content_kg).toBe('0.6000');
  expect(nitrogen.available_input_kg).toBe('0.1500');
  expect(nitrogen.shortfall_kg).toBe('0.3500');
  expect(data.result.biomass[0].unallocated_dry_kg).toBe('0.0000');
  await expect(page.getByRole('link', { name: 'Download nutrient CSV' })).toBeVisible();
  await expect(page.locator('#nutrient-report')).toContainText('Synthetic compost batch');
  await page.reload();
  await page.getByRole('button', { name: 'Use as draft' }).first().click();
  await expect(page.getByLabel('Enable nutrient and biomass budget', { exact: true })).toBeChecked();
  await expect(page.getByLabel('Feedstock name', { exact: true })).toHaveValue('Synthetic compost batch');
  await page.getByRole('button', { name: '+ Allocate biomass' }).click();
  await page.getByLabel('Allocation purpose').nth(2).selectOption('feed');
  await page.getByLabel('Allocation dry mass · kg', { exact: true }).nth(2).fill('5');
  await page.getByRole('button', { name: 'Save and calculate 104 weeks' }).click();
  await expect(page.locator('.error[role="alert"]')).toContainText('beyond its dry mass');
});
